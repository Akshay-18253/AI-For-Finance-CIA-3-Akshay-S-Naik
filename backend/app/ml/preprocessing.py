"""Feature engineering and preprocessing pipeline for fraud detection.

Strictly avoids data leakage by computing transformers on training splits only.
Produces consistent feature sets across offline training and real-time inference.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder, StandardScaler

# Supported enum values to enforce schema consistency
TRANSACTION_TYPES = ["Payment", "Transfer", "Withdrawal", "Deposit"]
MERCHANT_CATEGORIES = [
    "Retail",
    "Grocery",
    "Travel",
    "Entertainment",
    "Electronics",
    "Online Services",
    "Other",
]

NUMERICAL_COLS = [
    "transaction_amount",
    "transaction_hour",
    "recent_transaction_count",
    "account_age_days",
    "location_distance",
    "previous_transaction_amount",
    "amount_to_prev_ratio",
    "amount_log",
    "is_night",
    "risk_flag_sum",
]

CATEGORICAL_COLS = [
    "transaction_type",
    "merchant_category",
]

BINARY_COLS = [
    "new_device",
    "international_transaction",
]


def engineer_features(df: pd.DataFrame) -> pd.DataFrame:
    """Derive financial domain features from raw transaction inputs."""
    data = df.copy()

    # Ensure binary columns are ints
    data["new_device"] = data["new_device"].astype(int)
    data["international_transaction"] = data["international_transaction"].astype(int)

    # 1. Ratio of current amount to historical average/previous transaction
    prev = data["previous_transaction_amount"].clip(lower=0.0)
    data["amount_to_prev_ratio"] = np.round(data["transaction_amount"] / (prev + 1.0), 3)

    # 2. Log-transformed amount to normalize heavy tails
    data["amount_log"] = np.round(np.log1p(data["transaction_amount"]), 3)

    # 3. Nocturnal activity indicator (hours 0-5 and 23)
    data["is_night"] = data["transaction_hour"].apply(lambda h: 1 if (h <= 5 or h >= 23) else 0)

    # 4. Composite risk flags
    data["risk_flag_sum"] = data["new_device"] + data["international_transaction"]

    return data


def create_preprocessor() -> ColumnTransformer:
    """Create a scikit-learn ColumnTransformer configured for transaction features."""
    return ColumnTransformer(
        transformers=[
            (
                "num",
                StandardScaler(),
                NUMERICAL_COLS,
            ),
            (
                "cat",
                OneHotEncoder(
                    categories=[TRANSACTION_TYPES, MERCHANT_CATEGORIES],
                    handle_unknown="ignore",
                    sparse_output=False,
                ),
                CATEGORICAL_COLS,
            ),
            (
                "bin",
                "passthrough",
                BINARY_COLS,
            ),
        ],
        remainder="drop",
    )


def get_feature_names(preprocessor: ColumnTransformer) -> list[str]:
    """Retrieve output feature names generated by the fitted ColumnTransformer."""
    cat_encoder = preprocessor.named_transformers_["cat"]
    cat_names = cat_encoder.get_feature_names_out(CATEGORICAL_COLS).tolist()
    return NUMERICAL_COLS + cat_names + BINARY_COLS
